from __future__ import annotations

import io
from pathlib import Path

from rich.console import Console

from edna2dwc.cli.app import app
from edna2dwc.common import findings

DOCS = Path(__file__).resolve().parent.parent / "docs"
FINDINGS_DOC = DOCS / "findings.md"
COMMANDS_DOC = DOCS / "commands.md"
END = "<!-- end of generated table -->"


def begin_marker(source: str) -> str:
    return f"<!-- generated by `just docs` from {source}: edit the code, not this table -->"


def command_list() -> str:
    output = io.StringIO()
    app.help_print([], console=Console(file=output, width=100, no_color=True))
    root_help = output.getvalue()
    commands = root_help[root_help.index("What you do:") : root_help.index("Options:")]
    return f"```text\n{commands.strip()}\n```"


GENERATED = {
    FINDINGS_DOC: (begin_marker("edna2dwc/common/findings.py"), findings.reference_table),
    COMMANDS_DOC: (begin_marker("the command docstrings in edna2dwc/cli/"), command_list),
}


def render_page(path: Path) -> str:
    begin, render = GENERATED[path]
    before, rest = path.read_text(encoding="utf-8").split(begin, 1)
    _, after = rest.split(END, 1)
    return f"{before}{begin}\n{render()}\n{END}{after}"


def main() -> None:
    for path in GENERATED:
        path.write_text(render_page(path), encoding="utf-8")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
